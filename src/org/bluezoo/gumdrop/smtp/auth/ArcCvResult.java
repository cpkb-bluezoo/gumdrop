package org.bluezoo.gumdrop.smtp.auth;

/**
 * Chain validation status ({@code cv=}) from an ARC-Seal header or from
 * overall chain validation (RFC 8617).
 *
 * @author <a href='mailto:dog@gnu.org'>Chris Burdess</a>
 * @see <a href="https://www.rfc-editor.org/rfc/rfc8617">RFC 8617 - ARC</a>
 */
public enum ArcCvResult {

    /** No ARC chain present or not yet validated. */
    NONE,

    /** The ARC chain validated successfully. */
    PASS,

    /** The ARC chain failed validation. */
    FAIL

}
