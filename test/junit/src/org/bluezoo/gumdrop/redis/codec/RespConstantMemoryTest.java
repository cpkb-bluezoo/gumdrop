package org.bluezoo.gumdrop.redis.codec;

import java.lang.management.ManagementFactory;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;

import org.junit.Test;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;

/**
 * Tests that the memory the decoder uses does not depend on the size of the
 * reply. A reply of a gibibyte is generated as it is fed, a buffer at a time,
 * and never held; what is measured is how many bytes the thread allocates
 * while it is read, which would grow with the reply if anything accumulated
 * it.
 *
 * @author <a href='mailto:dog@gnu.org'>Chris Burdess</a>
 */
public class RespConstantMemoryTest {

    private static final long GIB = 1L << 30;
    /** The most the decoder may allocate, whatever the size of the reply. */
    private static final long ALLOWANCE = 256 * 1024;

    /** Discards every chunk and counts them. */
    private static class Counting implements RespEventHandler {
        long bytes;
        long chunks;
        boolean ended;
        boolean skipped;

        @Override
        public void beginReply(boolean push) {
        }

        @Override
        public void endReply(boolean wasSkipped) {
            ended = true;
            skipped = wasSkipped;
        }

        @Override
        public ReplyFlow nullValue() {
            return ReplyFlow.CONTINUE;
        }

        @Override
        public ReplyFlow integer(long value) {
            return ReplyFlow.CONTINUE;
        }

        @Override
        public ReplyFlow doubleValue(double value) {
            return ReplyFlow.CONTINUE;
        }

        @Override
        public ReplyFlow booleanValue(boolean value) {
            return ReplyFlow.CONTINUE;
        }

        @Override
        public ReplyFlow bigNumber(String digits) {
            return ReplyFlow.CONTINUE;
        }

        @Override
        public ReplyFlow simpleString(String value) {
            return ReplyFlow.CONTINUE;
        }

        @Override
        public ReplyFlow error(String message) {
            return ReplyFlow.CONTINUE;
        }

        @Override
        public ReplyFlow beginAggregate(RespType kind, long length) {
            return ReplyFlow.CONTINUE;
        }

        @Override
        public ReplyFlow endAggregate() {
            return ReplyFlow.CONTINUE;
        }

        @Override
        public ReplyFlow beginString(RespType kind, long length, String format) {
            return ReplyFlow.CONTINUE;
        }

        @Override
        public ReplyFlow stringChunk(ByteBuffer chunk) {
            bytes += chunk.remaining();
            chunks++;
            return ReplyFlow.CONTINUE;
        }

        @Override
        public ReplyFlow endString() {
            return ReplyFlow.CONTINUE;
        }
    }

    /** Skips the reply after its first chunk. */
    private static final class SkipAfterFirstChunk extends Counting {
        @Override
        public ReplyFlow stringChunk(ByteBuffer chunk) {
            super.stringChunk(chunk);
            return ReplyFlow.SKIP;
        }
    }

    /** Wants nothing: the handler of a reply to a command that timed out. */
    private static final class Null extends Counting {
        @Override
        public ReplyFlow beginString(RespType kind, long length, String format) {
            return ReplyFlow.SKIP;
        }
    }

    private static long allocated() {
        com.sun.management.ThreadMXBean bean =
                (com.sun.management.ThreadMXBean) ManagementFactory.getThreadMXBean();
        return bean.getThreadAllocatedBytes(Thread.currentThread().getId());
    }

    /**
     * Feeds a bulk string of the given size, in chunks of the given size,
     * the payload generated by reusing one buffer, and returns the bytes
     * allocated doing so.
     */
    private static long feed(long size, int chunk, Counting handler) throws RespException {
        RespDecoder decoder = new RespDecoder();
        decoder.setMaxSkip(2 * GIB);
        byte[] body = new byte[chunk];
        ByteBuffer header = ByteBuffer.wrap(("$" + size + "\r\n").getBytes(StandardCharsets.US_ASCII));
        ByteBuffer data = ByteBuffer.wrap(body);
        ByteBuffer trailer = ByteBuffer.wrap("\r\n".getBytes(StandardCharsets.US_ASCII));
        long before = allocated();
        decoder.receive(header, handler);
        long left = size;
        while (left > 0) {
            int n = (int) Math.min(chunk, left);
            data.clear();
            data.limit(n);
            decoder.receive(data, handler);
            assertEquals(0, data.remaining());
            left -= n;
        }
        decoder.receive(trailer, handler);
        long used = allocated() - before;
        assertTrue(decoder.isIdle());
        assertTrue(handler.ended);
        return used;
    }

    @Test
    public void aGibibyteIsDiscardedInConstantMemory() throws RespException {
        int[] chunks = {4096, 64 * 1024, 256 * 1024};
        for (int i = 0; i < chunks.length; i++) {
            Counting h = new Counting();
            long used = feed(GIB, chunks[i], h);
            assertEquals(GIB, h.bytes);
            assertTrue("chunk " + chunks[i] + " allocated " + used, used < ALLOWANCE);
        }
    }

    @Test
    public void aReplyNobodyWantsIsDiscardedInConstantMemory() throws RespException {
        Null h = new Null();
        long used = feed(GIB, 64 * 1024, h);
        assertEquals(0, h.bytes);
        assertTrue(h.skipped);
        assertTrue("allocated " + used, used < ALLOWANCE);
    }

    @Test
    public void aReplySkippedAfterTheFirstChunkIsDiscardedInConstantMemory() throws RespException {
        SkipAfterFirstChunk h = new SkipAfterFirstChunk();
        long used = feed(GIB, 64 * 1024, h);
        assertEquals(1, h.chunks);
        assertEquals(64 * 1024, h.bytes);
        assertTrue(h.skipped);
        assertTrue("allocated " + used, used < ALLOWANCE);
    }

    @Test
    public void allocationDoesNotGrowWithTheSizeOfTheReply() throws RespException {
        // warm up, then compare a small reply with one a thousand times larger
        feed(1L << 20, 64 * 1024, new Counting());
        long small = feed(1L << 20, 64 * 1024, new Counting());
        long large = feed(1L << 30, 64 * 1024, new Counting());
        assertTrue("small " + small + " large " + large, large <= small + 64 * 1024);
    }

    @Test
    public void aGibibyteInsideAnAggregateIsDiscardedInConstantMemory() throws RespException {
        RespDecoder decoder = new RespDecoder();
        Counting h = new Counting();
        byte[] body = new byte[64 * 1024];
        ByteBuffer data = ByteBuffer.wrap(body);
        long before = allocated();
        decoder.receive(ByteBuffer.wrap(("*2\r\n$" + GIB + "\r\n").getBytes(StandardCharsets.US_ASCII)), h);
        for (long left = GIB; left > 0; left -= body.length) {
            data.clear();
            decoder.receive(data, h);
        }
        decoder.receive(ByteBuffer.wrap("\r\n:1\r\n".getBytes(StandardCharsets.US_ASCII)), h);
        long used = allocated() - before;
        assertTrue(decoder.isIdle());
        assertEquals(GIB, h.bytes);
        assertTrue("allocated " + used, used < ALLOWANCE);
    }

}
